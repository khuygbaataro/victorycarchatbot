// Цэсийн товчийн тогтмол хариултууд (AI-гүй, шууд)
export function lizingText() {
  const l = DEALER.lizing;
  return (
    '🏦 Лизингийн нөхцөл:\n\n' +
    `• Урьдчилгаа: ${l.downPayment}\n` +
    `• Сарын хүү: ${l.monthlyRate}\n\n` +
    'Тодорхой машины нөхцлийг мэдэхийг хүсвэл загвараа бичээрэй.'
  );
}

export function locationText() {
  let msg = '📍 Хаяг байршил:\n' + DEALER.address;
  if (DEALER.mapUrl) msg += `\n\n🗺 Газрын зураг:\n${DEALER.mapUrl}`;
  if (DEALER.hours) msg += `\n\n🕒 Цаг: ${DEALER.hours}`;
  return msg;
}

export function contactText() {
  return `📲 Холбоо барих:\nУтас: ${DEALER.phone}\nХаяг: ${DEALER.address}`;
}
